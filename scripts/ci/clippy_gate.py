#!/usr/bin/env python3
"""Zero-tolerance gate for the two clippy categories that report probable bugs.

`clippy::correctness` and `clippy::suspicious` are the categories clippy itself
labels as "probably a bug" rather than "could be nicer", so a finding there is not a
style preference and has no business being counted on a sliding scale. This gate runs
clippy with both categories denied: any hit is a hard failure, and there is no
baseline file to keep in step with a toolchain upgrade.

Three ways this could silently stop checking anything, each with its own floor:

  * cargo never reached clippy (missing component, broken lock) -> exit code is not 0
    and no artifact line was parsed, which is reported as "no verdict", not as green;
  * the JSON stream was not read at all -> `--message-format json` output is parsed
    line by line and the run must show a compiled artifact for the `steamworks` lib,
    otherwise the gate refuses to answer;
  * the failure is a compile error unrelated to the two categories -> that is still
    red, but the message says so instead of claiming "0 suspicious findings".

Exit codes: 0 clean, 1 a denied lint fired, 2 the gate could not establish a verdict.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

DENIED = ("clippy::correctness", "clippy::suspicious")
# Cargo names the library target with an underscore, unlike the package name.
TARGETS = ("steamworks", "steamworks_sys")
# Measured by scanning the hand-written sources: one item-level allow, reviewed and
# unrelated to the denied categories (`html_surface.rs:515 too_many_arguments`).
SUPPRESSION_BASELINE = 1
# Floor on the number of files the suppression scan looks at. A scan that reads almost
# nothing would report an empty ledger and look like compliance.
MIN_SCANNED_FILES = 30
SUPPRESSION = re.compile(r"#!?\[[^\]]*?(allow|expect)\(clippy::")


def find_suppressions():
    found = []
    scanned = 0
    for root in (Path("src"), Path("steamworks-sys") / "src"):
        for path in sorted(root.rglob("*.rs")):
            if "bindings" in path.name:
                continue  # generated by bindgen, not a place a reviewer edits
            scanned += 1
            for number, line in enumerate(
                path.read_text(encoding="utf-8", errors="replace").splitlines(), 1
            ):
                if SUPPRESSION.search(line):
                    found.append(f"{path.as_posix()}:{number}: {line.strip()}")
    if scanned < MIN_SCANNED_FILES:
        print(
            f"::error:: the suppression scan saw {scanned} sources, expected at least "
            f"{MIN_SCANNED_FILES} -- an empty ledger would otherwise be mistaken for clean"
        )
        sys.exit(2)
    return found


def run(extra_features):
    cmd = [
        "cargo",
        "clippy",
        "--locked",
        "--all-targets",
        *extra_features,
        "--message-format",
        "json",
        "--",
    ]
    for category in DENIED:
        cmd += ["-D", category]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    return proc, cmd


def main():
    features = sys.argv[1:] or ["--all-features"]
    proc, cmd = run(features)
    denials = []
    seen = set()
    artifacts = set()
    other_errors = []
    unparsed = 0

    for line in proc.stdout.splitlines():
        line = line.strip()
        if not line.startswith("{"):
            continue
        try:
            message = json.loads(line)
        except json.JSONDecodeError:
            unparsed += 1
            continue
        reason = message.get("reason")
        if reason == "compiler-artifact":
            target = (message.get("target") or {}).get("name")
            if target:
                artifacts.add(target)
        elif reason == "compiler-message":
            diagnostic = message.get("message") or {}
            code = (diagnostic.get("code") or {}).get("code") or ""
            if diagnostic.get("level") != "error":
                continue
            # The command denies exactly two clippy categories, so a clippy-coded *error*
            # can only have come from them -- the category itself is not part of the code
            # string (`clippy::from_raw_with_void_ptr`, not `clippy::suspicious::...`).
            if code.startswith("clippy::"):
                spans = [s for s in diagnostic.get("spans", []) if s.get("is_primary")]
                where = spans[0] if spans else (diagnostic.get("spans") or [{}])[0]
                key = (code, where.get("file_name"), where.get("line_start"))
                if key in seen:
                    continue
                seen.add(key)
                denials.append(
                    f"{code}: {where.get('file_name', '?')}:{where.get('line_start', '?')} "
                    f"-- {diagnostic.get('message', '')}"
                )
            else:
                other_errors.append(f"{code or 'uncoded'}: {diagnostic.get('message', '')}")

    if denials:
        for denial in denials:
            print(f"::error:: {denial}")
        print(
            f"\n{len(denials)} correctness/suspicious finding(s). These are not style: clippy "
            "files them under 'probably a bug'. Fix the code. A missing artifact for the crate "
            "that failed is expected here -- the finding is the verdict, not a broken scan."
        )
        return 1

    if other_errors:
        print(
            "::error:: the build failed for a reason outside the two denied categories, so this "
            f"gate could not judge them: {other_errors[0]}",
            file=sys.stderr,
        )
        return 2

    if proc.returncode != 0:
        print(
            "::error:: clippy exited %d without a single parsed diagnostic -- the gate has no "
            "verdict, so it refuses to report clean. Command: %s\n%s"
            % (proc.returncode, " ".join(cmd), "\n".join(proc.stderr.splitlines()[-25:])),
            file=sys.stderr,
        )
        return 2

    missing = [name for name in TARGETS if name not in artifacts]
    if missing:
        print(
            f"::error:: no compiled artifact for {missing} -- clippy did not look at every crate, "
            f"so 'clean' would be an empty scan (artifacts seen: {sorted(artifacts)})",
            file=sys.stderr,
        )
        return 2

    if unparsed:
        print(
            f"::error:: {unparsed} JSON lines from the cargo stream did not parse -- the reader "
            f"is guessing at the rest",
            file=sys.stderr,
        )
        return 2

    # The deny-list above only sees what reaches the lint checker: an `#[allow]` in the
    # source silences this gate the same way it silences clippy. So the suppressions
    # themselves are registered, and the ledger is the disclosure -- a new one is red here
    # rather than an unexplained absence of findings.
    suppressed = find_suppressions()
    if len(suppressed) > SUPPRESSION_BASELINE:
        for line in suppressed:
            print(f"  {line}")
        print(
            f"::error:: {len(suppressed)} clippy suppressions in the sources, {SUPPRESSION_BASELINE} "
            "registered -- an allow is this gate's blind spot, so adding one has to be a deliberate, "
            "reviewed act."
        )
        return 1
    if len(suppressed) < SUPPRESSION_BASELINE:
        print(
            f"::error:: only {len(suppressed)} clippy suppressions remain against {SUPPRESSION_BASELINE} "
            "registered -- tighten SUPPRESSION_BASELINE to the truth and say why in the commit."
        )
        return 1

    print(
        f"clean: 0 correctness/suspicious findings across {len(artifacts)} compiled targets; "
        f"{len(suppressed)} registered clippy suppression(s) in the sources"
    )
    for line in suppressed:
        print(f"  registered: {line}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
